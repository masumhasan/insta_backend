async function seedFullInventory() {
  await connectDatabase();
  for (const item of itemsToUpsert) {
    await Inventory.findOneAndUpdate(
      { product: item.product },
      { $set: item },
      { upsert: true, new: true }
    );
  }
  await Inventory.updateMany(
    { product: { $regex: /rider/i }, itemType: { $exists: false } },
    { $set: { itemType: 'Rider' } }
  );
  await Inventory.updateMany(
    { product: { $regex: /post/i }, itemType: { $exists: false } },
    { $set: { itemType: 'Sign post' } }
  );
  await Inventory.updateMany(
    { product: { $regex: /panel/i }, itemType: { $exists: false } },
    { $set: { itemType: 'Main Panel' } }
  );
  const total = await Inventory.countDocuments();
  console.log(`[Seed] Inventory updated successfully! Total items: ${total}`);
  await disconnectDatabase();
}

seedFullInventory().catch(console.error);

